const cache = new Map();
function getJSON(path) {
  if (!cache.has(path)) {
    const p = fetch(path)
      .then(r => { if (!r.ok) throw new Error(`Could not load ${path} (${r.status})`); return r.json(); })
      .catch(e => { cache.delete(path); throw e; });
    cache.set(path, p);
  }
  return cache.get(path);
}
const pad3 = n => String(n).padStart(3, '0');
const D = {
  meta: () => getJSON('data/meta.json'),
  canons: async () => {
    const a = await getJSON('data/canons.json');
    if (!a.byId) a.byId = new Map(a.map(c => [c.id, c]));
    return a;
  },
  canon: id => getJSON(`data/canon/${id}.json`),
  cases: async () => {
    const d = await getJSON('data/cases.json');
    if (!d.bySlug) d.bySlug = new Map(d.cases.map(c => [c[0], c]));
    return d;
  },
  caseShard: async cl => { const m = await D.meta(); return getJSON(`data/case/${pad3(cl % m.nShards)}.json`); },
  detail: async uid => {
    const m = await D.meta();
    const s = await getJSON(`data/detail/${pad3(Number(uid) % m.nShards)}.json`);
    return s[uid];
  },
  justices: async () => {
    const a = await getJSON('data/justices.json');
    if (!a.byName) a.byName = new Map(a.map(j => [j.name, j]));
    return a;
  },
};

/* --------------------------------------------------------------- helpers */
const esc = s => String(s ?? '').replace(/[&<>"']/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));
const fmt = n => Number(n ?? 0).toLocaleString('en-US');
const pct = (a, b, d = 1) => (b ? (100 * a / b).toFixed(d) + '%' : '–');
const norm = s => String(s ?? '').toLowerCase().normalize('NFD').replace(/[̀-ͯ]/g, '').replace(/[^a-z0-9§]+/g, ' ');
const tokens = q => norm(q).split(' ').filter(Boolean);
const matchAll = (hay, toks) => toks.every(t => hay.includes(t));
const debounce = (fn, ms = 150) => { let t; return (...a) => { clearTimeout(t); t = setTimeout(() => fn(...a), ms); }; };
const TYPE_LABEL = { language: 'Language', substantive: 'Substantive', 'meta-canon': 'Meta-canon' };
const typeBadge = t => `<span class="badge type-${t === 'meta-canon' ? 'meta' : t}">${esc(TYPE_LABEL[t] || t)}</span>`;
const OPT_SHORT = { L: 'Lead opinion', C: 'Concurrence', P: 'Concurring in part, dissenting in part', D: 'Dissent', S: 'Statement respecting an order', H: 'On rehearing', M: 'Combined opinion text' };
const USAGE_SHORT = { A: 'Applied', C: 'Conditions not met', O: 'Outweighed', N: 'Not applied (other reason)', R: 'Rejected', U: 'Unclear' };
const courtListener = (cl, slug) => `https://www.courtlistener.com/opinion/${cl}/${encodeURIComponent(slug)}/`;
const tile = (v, label) => `<div class="tile"><div class="v">${v}</div><div class="l">${label}</div></div>`;
const paperRef = () => (CONFIG.paperUrl ? `<a href="${esc(CONFIG.paperUrl)}">${CONFIG.citationHtml}</a>` : CONFIG.citationHtml);
const justiceLink = (name, justices) => (justices.byName.has(name) ? `<a href="#/justice/${encodeURIComponent(name)}">${esc(name)}</a>` : esc(name));

function setQuery(path, obj) {
  const p = new URLSearchParams();
  for (const [k, v] of Object.entries(obj)) if (v !== '' && v != null && v !== false) p.set(k, v === true ? '1' : v);
  const qs = p.toString();
  history.replaceState(null, '', `#${path}${qs ? '?' + qs : ''}`);
}

function niceTicks(max, n = 4) {
  if (max <= 0) return [0, 1];
  const raw = max / n, mag = 10 ** Math.floor(Math.log10(raw));
  const step = [1, 2, 2.5, 5, 10].map(k => k * mag).find(s => s >= raw);
  const out = [];
  for (let i = 0; i * step < max + step * 1e-9; i++) out.push(+(i * step).toPrecision(12));
  if (out[out.length - 1] < max) out.push(+(out.length * step).toPrecision(12));
  return out;
}

function barChart(values, decades, { height = 230, fmtY = fmt, title = '', muted = [] } = {}) {
  const W = 960, H = height, m = { l: 56, r: 12, t: 12, b: 30 };
  const iw = W - m.l - m.r, ih = H - m.t - m.b;
  const ticks = niceTicks(Math.max(0, ...values.filter(v => v != null)));
  const top = ticks[ticks.length - 1] || 1;
  const bw = iw / values.length;
  let s = `<svg class="chart" viewBox="0 0 ${W} ${H}" role="img" aria-label="${esc(title)}">`;
  for (const t of ticks) {
    const y = (m.t + ih - ih * t / top).toFixed(1);
    s += `<line class="grid" x1="${m.l}" x2="${W - m.r}" y1="${y}" y2="${y}"/><text class="ytick" x="${m.l - 8}" y="${+y + 4}">${fmtY(t)}</text>`;
  }
  values.forEach((v, i) => {
    if (v == null) return;
    const h = ih * v / top, x = m.l + i * bw + bw * 0.12;
    s += `<rect class="bar${muted[i] ? ' muted' : ''}" x="${x.toFixed(1)}" y="${(m.t + ih - h).toFixed(1)}" width="${(bw * 0.76).toFixed(1)}" height="${Math.max(h, v > 0 ? 1 : 0).toFixed(1)}"><title>${decades[i]}s: ${fmtY(v)}${muted[i] ? ' (few cases in this decade)' : ''}</title></rect>`;
  });
  decades.forEach((d, i) => { if (d % 20 === 0) s += `<text class="xtick" x="${(m.l + i * bw + bw / 2).toFixed(1)}" y="${H - 9}">${d}</text>`; });
  return s + '</svg>';
}

function spark(dec) {
  const W = 100, H = 22, max = Math.max(...dec) || 1, bw = W / dec.length;
  let s = `<svg class="spark" viewBox="0 0 ${W} ${H}" preserveAspectRatio="none" aria-hidden="true">`;
  dec.forEach((v, i) => {
    if (!v) return;
    const h = Math.max(1, H * v / max);
    s += `<rect x="${(i * bw).toFixed(2)}" y="${(H - h).toFixed(2)}" width="${(bw * 0.8).toFixed(2)}" height="${h.toFixed(2)}"/>`;
  });
  return s + '</svg>';
}

function hbars(entries, total) {
  const max = Math.max(1, ...entries.map(e => e[1]));
  return `<ul class="hbars">${entries.map(([label, n, href]) => `<li>
    <span class="hl" title="${esc(label)}">${href ? `<a href="${href}">${esc(label)}</a>` : esc(label)}</span>
    <span class="hb"><span style="width:${(100 * n / max).toFixed(1)}%"></span></span>
    <span class="hn">${fmt(n)}${total ? ` <small>${pct(n, total)}</small>` : ''}</span></li>`).join('')}</ul>`;
}

const quoteFragments = quote => String(quote || '')
  .split(/\s*(?:\.\s?\.\s?\.|…)\s*/)
  .map(s => s.trim().replace(/^["“”'‘’]+|["“”'‘’]+$/g, '').trim())
  .filter(s => s.length >= 20);

function highlight(par, quote) {
  let out = esc(par);
  for (const f of quoteFragments(quote)) {
    const ef = esc(f), i = out.indexOf(ef);
    if (i >= 0) out = `${out.slice(0, i)}<mark>${ef}</mark>${out.slice(i + ef.length)}`;
  }
  return out;
}

// Each observation shows its quotation and, on request, the surrounding passage (trimmed at build time).
// The full opinion is a link to CourtListener.
function obsItem(o, justices, { head = 'case' } = {}) {
  const year = (o.date || '').slice(0, 4);
  const author = o.author ? justiceLink(o.author, justices) : '<span>Author not recorded</span>';
  const ei = o.ei === 'E' ? 'Explicit' : o.ei === 'I' ? 'Implicit' : '–';
  const cl = `<a class="ext" href="${courtListener(o.cl, o.cs || o.slug)}" target="_blank" rel="noopener">Full opinion on CourtListener&nbsp;↗</a>`;
  const headHtml = head === 'case'
    ? `<div class="obs-head"><span class="year">${esc(year)}</span><a href="#/case/${encodeURIComponent(o.slug)}">${esc(o.case)}</a>${cl}</div>`
    : '';
  return `<li class="obs" data-cl="${esc(o.cl)}" data-slug="${esc(o.slug)}">${headHtml}
    <div class="obs-meta">${author} · ${esc(OPT_SHORT[o.opt] || 'Opinion type not recorded')} · <span class="badge ei-${esc(o.ei)}">${ei}</span>${o.usage ? ` <span class="badge use-${esc(o.usage)}">${esc(USAGE_SHORT[o.usage] || '')}</span>` : ''}${head === 'case' ? '' : ` · ${cl}`}</div>
    ${o.quote ? `<blockquote>${esc(o.quote)}</blockquote>` : ''}
    <button type="button" class="more" data-uid="${esc(o.uid)}" aria-expanded="false">Show context</button>
    <div class="detail" hidden></div></li>`;
}

function wireDetails(container) {
  container.addEventListener('click', async e => {
    const btn = e.target.closest('button.more');
    if (!btn) return;
    const li = btn.closest('li'), box = li.querySelector('.detail');
    if (!box.hidden) { box.hidden = true; btn.textContent = 'Show context'; btn.setAttribute('aria-expanded', 'false'); return; }
    btn.textContent = 'Loading…';
    try {
      const d = await D.detail(btn.dataset.uid);
      const q = li.querySelector('blockquote')?.textContent || '';
      box.innerHTML = d
        ? `<p class="para">${highlight(d.p, q)}</p>${d.s ? `<p class="restate"><span>The canon as stated for this passage:</span> ${esc(d.s)}</p>` : ''}`
        : '<p class="muted">No passage is available for this observation.</p>';
      box.hidden = false;
      btn.textContent = 'Hide context';
      btn.setAttribute('aria-expanded', 'true');
    } catch (err) {
      btn.textContent = 'Show context';
      box.innerHTML = `<p class="error">${esc(err.message)}</p>`;
      box.hidden = false;
    }
  });
}

function pager(total, page, onGo) {
  const pages = Math.max(1, Math.ceil(total / PAGE_SIZE));
  const el = document.createElement('div');
  el.className = 'pager';
  if (pages <= 1) return el;
  el.innerHTML = `<button type="button" data-p="${page - 1}" ${page <= 1 ? 'disabled' : ''}>← Previous</button>
    <span>Page ${page} of ${fmt(pages)}</span>
    <button type="button" data-p="${page + 1}" ${page >= pages ? 'disabled' : ''}>Next →</button>`;
  el.addEventListener('click', e => { const b = e.target.closest('button[data-p]'); if (b && !b.disabled) onGo(+b.dataset.p); });
  return el;
}

function sortRows(rows, key, dir) {
  const m = dir === 'asc' ? 1 : -1;
  return rows.slice().sort((a, b) => {
    const x = a[key], y = b[key];
    if (x == null && y == null) return 0;
    if (x == null) return 1;
    if (y == null) return -1;
    return (typeof x === 'string' ? x.localeCompare(y) : x - y) * m;
  });
}

