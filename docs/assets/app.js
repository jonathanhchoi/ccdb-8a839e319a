async function route() {
  const hash = location.hash;
  if (hash && !hash.startsWith('#/')) return;   // in-page anchors such as the skip link
  const [path, qs] = (hash.slice(1) || '/').split('?');
  const params = new URLSearchParams(qs || '');
  const main = document.getElementById('app');
  const view = document.createElement('div');
  view.innerHTML = '<p class="loading">Loading…</p>';
  main.replaceChildren(view);
  window.scrollTo(0, 0);
  for (const [re, fn, sec] of ROUTES) {
    const m = path.match(re);
    if (!m) continue;
    document.querySelectorAll('#nav a').forEach(a => a.classList.toggle('on', !!sec && a.dataset.sec === sec));
    try {
      await fn(view, params, ...m.slice(1).map(decodeURIComponent));
    } catch (e) {
      console.error(e);
      view.innerHTML = `<div class="error">Something went wrong loading this page: ${esc(e.message)}</div>`;
    }
    return;
  }
  notFound(view);
}

